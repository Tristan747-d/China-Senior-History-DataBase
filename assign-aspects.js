function matchAspects(ev) {
  const set = new Set();
  const text = [ev.title, ev.detail, ev.note].filter(Boolean).join(' ');
  for (const [re, aspects] of RULES) {
    if (re.test(text)) aspects.forEach(a => set.add(a));
  }
  return [...set];
}

const events = JSON.parse(await readFile(DATA_FILE, 'utf8'));
let byRule = 0, byOverride = 0, none = 0;
const unmatched = [];

for (const ev of events) {
  let aspects = matchAspects(ev);
  if (OVERRIDES[ev.title]) {
    aspects = [...new Set([...OVERRIDES[ev.title]])];
    byOverride++;
  } else if (aspects.length) {
    byRule++;
  } else {
    none++;
    unmatched.push(ev.title);
    aspects = ['政治']; // 兜底：政治事件占绝大多数
  }
  ev.aspects = aspects;
}

await writeFile(DATA_FILE, JSON.stringify(events, null, 2), 'utf8');
console.log(`规则匹配 ${byRule}，人工覆盖 ${byOverride}，兜底政治 ${none}`);
const stat = { '经济': 0, '政治': 0, '文化': 0 };
let multi = 0;
for (const ev of events) {
  for (const a of ev.aspects) stat[a]++;
  if (ev.aspects.length > 1) multi++;
}
console.log('标签分布:', stat, '（多标签', multi, '条）');
if (unmatched.length) console.log('兜底（未匹配）:\n  ' + unmatched.join('\n  '));

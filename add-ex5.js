    id: `ex5_${String(existing.length + i).padStart(3, '0')}`,
    title, category: 'china',
    scale: 'year', era: era === 'BCE' ? 'BCE' : 'CE',
    year, month: null, day: null, century: null,
    sortYear: era === 'BCE' ? -year : year,
    regions: ['东亚'],

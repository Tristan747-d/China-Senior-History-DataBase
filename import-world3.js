// ===== 校验：标题唯一性 + 重复检测 =====
const existing = JSON.parse(await readFile(DATA_FILE, 'utf8'));
const existTitles = new Set(existing.map(e => e.title));
const newTitles = new Set();
const dupInDoc = [];
for (const r of rows) {
  if (newTitles.has(r[5])) dupInDoc.push(r[5]);
  newTitles.add(r[5]);
}
const dupWithExisting = rows.filter(r => existTitles.has(r[5])).map(r => r[5]);
if (dupInDoc.length) { console.error('文档内重复标题：', dupInDoc); process.exit(1); }
if (dupWithExisting.length) { console.error('与库内重复标题：', dupWithExisting); process.exit(1); }

// ===== 构建 =====
const baseId = existing.length;
const startIdNum = existing.filter(e => e.id.startsWith('w3_')).length; // 幂等计数
let made = 0;
const newEvents = rows.map((r, i) => {
  const [timeText, era, year, month, day, title, regions, detail, note] = r;
  const notes = [];
  if (!/^\d+年(\d+月)?(\d+日)?$/.test(timeText) && timeText !== '二战后') notes.push(`原文时间：${timeText}`);
  if (note) notes.push(note);
  const idNum = String(baseId + i).padStart(3, '0');
  return {
    id: `w3_${idNum}`,
    title, category: 'world', scale: month ? 'date' : 'year',
    era, year, month, day, century: null,
    sortYear: era === 'BCE' ? -year : year,
    regions, detail,
    note: notes.join('；') || null,
    location: null, tags: [],
    createdAt: new Date().toISOString(),
  };
});

// 幂等：如已导入（按 id 前缀 w3_ 计数相同则跳过）
const alreadyW3 = existing.filter(e => e.id.startsWith('w3_'));
let all;
if (alreadyW3.length) {
  console.log(`检测到已导入 ${alreadyW3.length} 条 w3_ 事件，跳过（如需重导请先删除 w3_ 条目）`);
  all = existing;
} else {
  all = [...existing, ...newEvents];
  made = newEvents.length;
  all.sort((a, b) => a.sortYear - b.sortYear || (a.month || 0) - (b.month || 0) || (a.day || 0) - (b.day || 0));
  await writeFile(DATA_FILE, JSON.stringify(all, null, 2), 'utf8');
}

// ===== 校验：regions 非空 =====
const noRegion = all.filter(e => !Array.isArray(e.regions) || !e.regions.length);
console.log(`本次导入 ${made} 条；总 ${all.length} 条`);
console.log(`校验通过：标题全部唯一、regions 全部非空（${noRegion.length} 条例外）`);

function geocode(title, regions) {
  for (const [kw, , lat, lng] of CITIES) {
    if (title.includes(kw)) return { lat, lng, source: `title:${kw}` };
  }
  const r = regions.find(x => CENTROIDS[x]);
  if (r) {
    const c = CENTROIDS[r];
    const jitter = () => (Math.random() - 0.5) * 6;
    return { lat: +(c[0] + jitter()).toFixed(3), lng: +(c[1] + jitter()).toFixed(3), source: `centroid:${r}` };
  }
  return null;
}

// aspects 判定（简版：标题+详情关键词）
function assignAspects(title, detail) {
  const t = title + detail;
  const a = new Set();
  if (/经济|财政|赋税|税|关税|货币|金融|银行|保险|金本位|法币|金圆券|厘金|海关|所得税|一条鞭|摊丁|永不加赋|布雷顿|民生日用|农业|垦|社保|社会保障|福利|劳动保险|土地/.test(t)) a.add('经济');
  if (/政治|改革|变法|政变|宪|共和|帝|王朝|议会|选举|普选|文官|公务员|官制|选官|科举|察举|中正|法律|法典|条约|协定|国联|国际|建交|论坛|机制|自治|民族|法|法系|律师|立法|主权|训政|行宪|苏维埃|三三制|荣辱观|纲要|维新|新政|统一|战争|和约|诏书|帝国|户籍|诏|敕|礼/.test(t)) a.add('政治');
  if (/文化|教育|学堂|学制|思想|观|价值观|礼|经|书|学/.test(t)) a.add('文化');
  if (!a.size) a.add('政治');
  return [...a];
}


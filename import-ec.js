function geocode(title, regions) {
  for (const [kw, , lat, lng] of CITIES) {
    if (title.includes(kw)) return { lat, lng, source: `title:${kw}` };
  }
  const r = regions.find(x => CENTROIDS[x]);
  if (r) {
    const c = CENTROIDS[r];
    const jitter = () => (Math.random() - 0.5) * 6;
    return { lat: +(c[0] + jitter()).toFixed(3), lng: +(c[1] + jitter()).toFixed(3), source: `centroid:${r}` };
  }
  return null;
}

function assignAspects(title, detail) {
  const t = title + detail;
  const a = new Set();
  if (/经济|商业|贸易|货币|银行|金融|证券|交易所|股份|公司|物流|邮政|粮食|食品|农业|畜|驯|铁路|公路|高速|汽车|飞机|汽船|自行车|电信|计算机|互联网|技术|交通|工厂|劳工|罢工|劳动|保险|工厂法|交易所|铸币|铜块|合约|苦力|金矿|淘金|火|潜|深潜/.test(t)) a.add('经济');
  if (/政治|战争|起义|王国|帝国|分裂|独立|运动|政府|政府|法令|法|条例|宪章|公约|圣殿|使团|蒙古|西征|入侵|卫|议|会议|政策|体制|卫国/.test(t)) a.add('政治');
  if (/文化|文字|儒|佛|汉字|教育|学校|图书馆|博物|文物|古迹|遗产|非遗|医学|病|疫|医|接种|青霉|消毒|卫生|文明|典籍|译|传播|宪章|保护/.test(t)) a.add('文化');
  if (!a.size) a.add('经济');
  return [...a];
}


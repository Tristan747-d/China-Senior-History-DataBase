function matchRegions(title, note) {
  const set = new Set();
  const text = title + ' ' + (note || '');
  for (const [re, regions] of RULES) {
    if (re.test(text)) regions.forEach(r => set.add(r));
  }
  return [...set];
}

const events = JSON.parse(await readFile(DATA_FILE, 'utf8'));
let multi = 0, none = 0;
for (const ev of events) {
  let regions = matchRegions(ev.title, ev.note);
  if (OVERRIDES[ev.id]) regions = [...new Set([...regions, ...OVERRIDES[ev.id]])];
  if (!regions.length) { none++; ev.regions = ['其他']; }
  else ev.regions = regions;
  if (regions.length > 1) multi++;
  delete ev.region; // 移除旧单值字段
}
await writeFile(DATA_FILE, JSON.stringify(events, null, 2), 'utf8');
console.log(`多区事件 ${multi} 条，无匹配（归'其他'） ${none} 条`);
const stat = {};
for (const ev of events) ev.regions.forEach(r => stat[r] = (stat[r] || 0) + 1);
console.log('标签分布:', Object.entries(stat).sort((a, b) => b[1] - a[1]));
if (none) {
  const list = events.filter(e => e.regions[0] === '其他');
  console.log('未匹配:', list.map(e => e.id + ' ' + e.title));
}

function buildEv(r, i) {
  const [timeText, era, year, month, day, title, note] = r;
  const notes = [];
  // 非精确年份的原文时间保留
  if (!/^(\d+年(\d+月(\d+日)?)?)$/.test(timeText) && !/(公元前|前)\d+年$/.test(timeText)) notes.push(`原文时间：${timeText}`);
  if (note) notes.push(note);
  return {
    id: `w2_${String(i).padStart(3, '0')}`,
    title, category: 'world', scale: month ? 'date' : 'year',
    era, year, month, day, century: null,
    sortYear: era === 'BCE' ? -year : year,
    location: null,
    note: notes.join('；') || null,
    tags: [], createdAt: new Date().toISOString(),
  };
}

const existing = JSON.parse(await readFile(DATA_FILE, 'utf8'));
const keep = existing.filter(e => e.category !== 'world');
const newEvents = rows.map(buildEv);
const all = [...keep, ...newEvents];
all.sort((a, b) => a.sortYear - b.sortYear || (a.month || 0) - (b.month || 0) || (a.day || 0) - (b.day || 0));
await writeFile(DATA_FILE, JSON.stringify(all, null, 2), 'utf8');
console.log(`保留中国史/其他 ${keep.length} 条，导入世界史文档条目 ${newEvents.length} 条，共 ${all.length} 条 ✓`);
